import assert from 'power-assert'

import { binaryToText, textToBinary } from '../src/funcs.js'

console.log(textToBinary('hello'))
console.log(binaryToText('01101000 01100101 01101100 01101100 01101111'))

assert(textToBinary('Hello World!') === '01001000 01100101 01101100 01101100 01101111 00100000 01010111 01101111 01110010 01101100 01100100 00100001')
assert(binaryToText('01001000 01100101 01101100 01101100 01101111 00100000 01010111 01101111 01110010 01101100 01100100 00100001') === 'Hello World!')

assert(binaryToText('0110100001100101011011000110110001101111') === 'hello')
assert(textToBinary('привет!!!!!') === '11010000 10111111 11010001 10000000 11010000 10111000 11010000 10110010 11010000 10110101 11010001 10000010 00100001 00100001 00100001 00100001 00100001')
